<?php
/**
 * Markdown report for sending to a developer.
 *
 * @package IWorksIE\SecurityAudit
 */

namespace IWorksIE\SecurityAudit\Support;

use IWorksIE\SecurityAudit\Vendor\IWorksIE\Core\Checks\Result;
use IWorksIE\SecurityAudit\Vendor\IWorksIE\Core\Report;

/**
 * Results + affected items. Never includes secret values.
 */
final class ReportBuilder {

	/**
	 * @param array<string,array<string,mixed>> $results Stored results.
	 * @return string
	 */
	public static function build( array $results ) {
		$objects = array();
		foreach ( $results as $id => $row ) {
			$objects[ $id ] = Result::from_array( (array) $row );
		}

		$markdown = Report::from_results(
			'iWorks.ie Security Audit report',
			$objects,
			array(
				'site' => home_url( '/' ),
				'wp'   => (string) get_bloginfo( 'version' ),
				'php'  => PHP_VERSION,
				'date' => gmdate( 'c' ),
			)
		);

		$details = '';
		foreach ( $objects as $result ) {
			if ( ! in_array( $result->status(), array( 'critical', 'recommended' ), true ) ) {
				continue;
			}
			$data = $result->data();
			if ( empty( $data['matches'] ) || ! is_array( $data['matches'] ) ) {
				continue;
			}
			$details .= "\n### " . $result->label() . "\n\n";
			foreach ( array_slice( $data['matches'], 0, 25 ) as $match ) {
				$match    = (array) $match;
				$line     = isset( $match['relative'] ) ? (string) $match['relative'] : '';
				$line    .= ! empty( $match['kind'] ) ? ' (' . (string) $match['kind'] . ( ! empty( $match['size'] ) ? ', ' . (string) $match['size'] : '' ) . ')' : '';
				$details .= '- ' . $line . "\n";
			}
		}
		if ( '' !== $details ) {
			$markdown .= "\n## Affected items\n" . $details;
		}

		$markdown .= "\n---\n";
		$markdown .= "Generated by iWorks.ie Security Audit. It contains no passwords, keys or salts.\n";
		$markdown .= "Need a hand fixing these? https://www.iworks.ie\n";
		return $markdown;
	}
}
